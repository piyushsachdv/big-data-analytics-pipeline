#!/usr/bin/env bash
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
export BIGDATA_ROOT="$ROOT/.runtime"
export JAVA_HOME="${JAVA_HOME:-/usr/lib/jvm/java-17-openjdk-amd64}"
export HADOOP_HOME="$BIGDATA_ROOT/hadoop"
export HADOOP_CONF_DIR="$HADOOP_HOME/etc/hadoop"
export YARN_CONF_DIR="$HADOOP_CONF_DIR"
export SPARK_HOME="$("$ROOT/.venv/bin/python" -c 'import pyspark; print(pyspark.__path__[0])' 2>/dev/null || true)"
export HIVE_CONF_DIR="$SPARK_HOME/conf"
export HADOOP_LOG_DIR="$BIGDATA_ROOT/logs/hadoop"
export HADOOP_PID_DIR="$BIGDATA_ROOT/pids/hadoop"
export YARN_LOG_DIR="$BIGDATA_ROOT/logs/yarn"
export YARN_PID_DIR="$BIGDATA_ROOT/pids/yarn"
export SPARK_LOCAL_DIRS="$BIGDATA_ROOT/tmp/spark"
export SPARK_LOCAL_IP="${SPARK_LOCAL_IP:-127.0.0.1}"
export PYSPARK_PYTHON="${PYSPARK_PYTHON:-$(command -v python3)}"
export PATH="$HADOOP_HOME/bin:$HADOOP_HOME/sbin:$SPARK_HOME/bin:$PATH"
mkdir -p "$HADOOP_LOG_DIR" "$HADOOP_PID_DIR" "$YARN_LOG_DIR" "$YARN_PID_DIR" "$SPARK_LOCAL_DIRS"
